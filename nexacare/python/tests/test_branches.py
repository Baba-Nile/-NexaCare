"""Branch data, build output, publishing rules and the site checker. Builds run in a temporary copy of the project.
Run:  python -m unittest discover -s python/tests -v   (from the project root)"""
import copy, json, re, shutil, subprocess, sys, tempfile, unittest
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
import branches as BM

def project_copy():
    d = Path(tempfile.mkdtemp()) / "site"
    shutil.copytree(ROOT, d, ignore=shutil.ignore_patterns("instance", "__pycache__", ".git", "*.db", "docs"))
    return d
def run(d, script):
    p = subprocess.run([sys.executable, str(d / "python" / script)], capture_output=True, text=True, cwd=d); return p.returncode, p.stdout + p.stderr
def edit_branch(d, slug, **changes):
    f = d / "data" / "branches.json"; j = json.loads(f.read_text(encoding="utf-8"))
    for b in j["branches"]:
        if b["slug"] == slug:
            for k, v in changes.items():
                if k == "verified": b["verified"].update(v)
                else: b[k] = v
    f.write_text(json.dumps(j, indent=1), encoding="utf-8")
SLUGS = ["maili-saba", "manor-house", "meru-farm", "tiwani", "eldoret", "nairobi"]
CENTRAL = "tel:+254726094695"

class Data(unittest.TestCase):
    def setUp(self): self.j = BM.load()
    def test_six_branches_in_order_and_main_centre_kept_separate(self):
        self.assertEqual([b["slug"] for b in self.j["branches"]], SLUGS); self.assertEqual(self.j["main_centre"]["name"], "Gatua, Kitale"); self.assertEqual(self.j["main_centre"]["role"], "main_centre")
    def test_data_is_valid_and_complete(self):
        self.assertEqual(BM.validate(self.j), [])
        for b in self.j["branches"]:
            for k in ("slug", "name", "locality", "address", "phone", "whatsapp", "email", "hours", "services", "coordinates", "directions_url", "status", "seo_title", "seo_description", "verified"): self.assertIn(k, b, f"{b['slug']} lacks {k}")
    def test_nothing_is_invented(self):
        for b in self.j["branches"]:
            self.assertEqual(b["status"], "details_pending"); self.assertFalse(any(b["verified"].values()), b["slug"])
            self.assertIsNone(b["address"]); self.assertIsNone(b["phone"]["tel"]); self.assertIsNone(b["email"]); self.assertEqual(b["services"], []); self.assertIsNone(b["coordinates"]["lat"])
            for f in BM.FACTS: self.assertIsNone(BM.value(b, f), f"{b['slug']}.{f} must not be public")
    def test_existing_central_contact_is_preserved(self):
        s = json.loads((ROOT / "data" / "site.json").read_text(encoding="utf-8")); self.assertEqual((s["phone"], s["email"], s["locality"]), ("+254 726 094 695", "nexacarehc@gmail.com", "Gatua, Kitale"))
    def test_unverified_values_stay_hidden_even_if_filled_in(self):
        b = copy.deepcopy(self.j["branches"][0]); b["phone"] = {"display": "0700 000 000", "tel": "+254700000000"}; b["address"] = "Some Road"
        self.assertIsNone(BM.value(b, "phone")); self.assertIsNone(BM.value(b, "address")); b["verified"]["phone"] = True; self.assertEqual(BM.value(b, "phone")["tel"], "+254700000000")
    def test_validator_catches_mistakes(self):
        j = copy.deepcopy(self.j); j["branches"][0]["verified"]["phone"] = True; self.assertTrue(any("verified but has no value" in x for x in BM.validate(j)))
        j = copy.deepcopy(self.j); j["branches"][1]["slug"] = "Bad Slug"; self.assertTrue(BM.validate(j))
        j = copy.deepcopy(self.j); j["branches"][2]["phone"] = {"display": "x", "tel": "abc"}; self.assertTrue(any("phone.tel" in x for x in BM.validate(j)))
        j = copy.deepcopy(self.j); j["branches"][3]["slug"] = j["branches"][4]["slug"]; self.assertTrue(any("duplicate" in x for x in BM.validate(j)))
        j = copy.deepcopy(self.j); j["branches"][4]["status"] = "open"; self.assertTrue(any("status is 'open'" in x for x in BM.validate(j)))
        j = copy.deepcopy(self.j); j["branches"].pop(); self.assertTrue(any("missing required branch" in x for x in BM.validate(j)))
    def test_directions_only_from_verified_sources(self):
        b = copy.deepcopy(self.j["branches"][0]); b["coordinates"] = {"lat": -1.28, "lng": 36.82}; self.assertIsNone(BM.directions_url(b))
        b["verified"]["directions"] = True; self.assertIn("destination=-1.28,36.82", BM.directions_url(b))

class Build(unittest.TestCase):
    """The committed build output (generated by python/build.py)."""
    def page(self, rel): return (ROOT / rel).read_text(encoding="utf-8")
    def test_every_branch_page_exists_with_unique_seo(self):
        titles, descs = set(), set()
        for s in SLUGS:
            h = self.page(f"branches/{s}.html"); t = re.search(r"<title>(.*?)</title>", h).group(1); d = re.search(r'name="description" content="(.*?)"', h).group(1)
            self.assertNotIn(t, titles); self.assertNotIn(d, descs); titles.add(t); descs.add(d); self.assertEqual(h.count("<h1"), 1)
    def test_pending_branch_pages_are_noindex_and_not_in_sitemap(self):
        sm = self.page("sitemap.xml")
        for s in SLUGS: self.assertIn("noindex", self.page(f"branches/{s}.html")[:2500]); self.assertNotIn(f"branches/{s}.html", sm)
        self.assertIn("branches/index.html", sm); self.assertNotIn("noindex", self.page("branches/index.html")[:2500])
    def test_no_unverified_contact_details_are_published(self):
        for f in list((ROOT).rglob("*.html")):
            if "python" in f.relative_to(ROOT).parts: continue
            h = f.read_text(encoding="utf-8")
            self.assertEqual(set(re.findall(r'href="(tel:[^"]*)"', h)) - {CENTRAL}, set(), f.name); self.assertNotIn("wa.me", h); self.assertNotIn("google.com/maps", h); self.assertNotIn("<iframe", h)
    def test_branch_page_contents(self):
        h = self.page("branches/eldoret.html")
        for need in ("NexaCare Eldoret", "Branch details", "Request an appointment at NexaCare Eldoret", 'value="eldoret" selected', "central line", "Coming soon"): self.assertIn(need, h)
        self.assertEqual(len(re.findall('application/ld\\+json', h)), 2)
        ld = json.loads(re.findall(r'<script type="application/ld\+json">(.*?)</script>', h)[0]); self.assertEqual(ld["@type"], "MedicalClinic"); self.assertNotIn("telephone", ld); self.assertNotIn("address", ld)
    def test_navigation_and_contact_cover_all_branches(self):
        for rel in ("index.html", "about.html", "contact.html", "services/laboratory.html", "health-library/index.html"):
            h = self.page(rel); self.assertIn("Our Branches", h); self.assertIn("Request Appointment", h)
            for s in SLUGS: self.assertIn(f"branches/{s}.html", h, f"{rel} -> {s}")
        c = self.page("contact.html"); [self.assertIn(n, c) for n in ("Maili Saba", "Manor House", "Meru Farm", "Tiwani", "Eldoret", "Nairobi", "Gatua, Kitale")]
    def test_forms_have_branch_selection_with_all_options(self):
        for rel, kind in (("appointments.html", "appointment"), ("contact.html", "contact"), ("homecare.html", "homecare"), ("index.html", "quick"), ("branches/nairobi.html", "appointment")):
            h = self.page(rel); m = re.search(r'<form class="form" data-enquiry="%s".*?</form>' % kind, h, re.S); self.assertTrue(m, rel)
            vals = re.findall(r'<option value="([^"]*)"', re.search(r'name="branch".*?</select>', m.group(0), re.S).group(0)); self.assertEqual([v for v in vals if v], SLUGS + ["gatua-kitale", "no-preference"], rel)
        a = self.page("appointments.html"); self.assertRegex(a, r'name="branch"[^>]*required')
    def test_no_inline_styles_for_csp(self):
        for f in ROOT.rglob("*.html"):
            if "python" in f.relative_to(ROOT).parts: continue
            self.assertNotRegex(f.read_text(encoding="utf-8"), r'\sstyle="', f.name)
    def test_old_pages_still_exist(self):
        for rel in ("index.html", "about.html", "services.html", "homecare.html", "appointments.html", "contact.html", "faq.html", "privacy.html", "terms.html", "404.html", "health-library/index.html", "services/outpatient.html", "health-library/malaria.html"): self.assertTrue((ROOT / rel).exists(), rel)

class Publishing(unittest.TestCase):
    """Builds in a temporary copy to prove verified details flow through, and unverified ones do not."""
    @classmethod
    def setUpClass(cls):
        cls.d = project_copy()
        edit_branch(cls.d, "eldoret", status="open", locality="Eldoret town", address="Example Road, Eldoret (test data)", phone={"display": "0700 111 222", "tel": "+254700111222"}, hours=["Mon to Fri, 8am to 5pm (test data)"], services=["laboratory", "pharmacy"],
                    coordinates={"lat": 0.5143, "lng": 35.2698}, verified={"locality": True, "address": True, "phone": True, "hours": True, "services": True, "directions": True}, hours_schema=["Mo-Fr 08:00-17:00"])
        cls.rc, cls.out = run(cls.d, "build.py"); cls.chk = run(cls.d, "check_site.py")
    def page(self, rel): return (self.d / rel).read_text(encoding="utf-8")
    def test_build_and_checker_pass(self): self.assertEqual(self.rc, 0, self.out); self.assertEqual(self.chk[0], 0, self.chk[1])
    def test_verified_facts_appear_on_the_branch_page_and_card(self):
        h = self.page("branches/eldoret.html")
        for need in ("Example Road, Eldoret", 'href="tel:+254700111222"', "Mon to Fri, 8am to 5pm", "Services at this branch", "Laboratory", "Get directions", "google.com/maps/dir/?api=1&amp;destination=0.5143,35.2698"): self.assertIn(need, h)
        hub = self.page("branches/index.html"); self.assertIn("tel:+254700111222", hub); self.assertIn("Directions", hub); self.assertIn("data-has-phone", hub); self.assertIn('data-filter="phone"', hub)
    def test_structured_data_contains_only_verified_facts(self):
        ld = json.loads(re.findall(r'<script type="application/ld\+json">(.*?)</script>', self.page("branches/eldoret.html"))[0])
        self.assertEqual(ld["telephone"], "+254700111222"); self.assertEqual(ld["geo"]["latitude"], 0.5143); self.assertEqual(ld["openingHours"], ["Mo-Fr 08:00-17:00"]); self.assertIn("streetAddress", ld["address"])
    def test_open_verified_branch_enters_sitemap_and_loses_noindex(self):
        self.assertIn("branches/eldoret.html", self.page("sitemap.xml")); self.assertNotIn("noindex", self.page("branches/eldoret.html")[:2500]); self.assertNotIn("branches/nairobi.html", self.page("sitemap.xml"))
    def test_other_branches_stay_clean(self):
        h = self.page("branches/nairobi.html"); self.assertNotIn("0700 111 222", h); self.assertNotIn("Example Road", h)
    def test_checker_catches_a_leaked_unverified_number(self):
        f = self.d / "branches" / "tiwani.html"; orig = f.read_text(encoding="utf-8")
        f.write_text(orig.replace("</main>", '<a href="tel:+254700999999">fake</a></main>'), encoding="utf-8")
        try: rc, out = run(self.d, "check_site.py"); self.assertEqual(rc, 1); self.assertIn("telephone link other than the central line", out)
        finally: f.write_text(orig, encoding="utf-8")
    def test_checker_catches_missing_branch_option(self):
        f = self.d / "appointments.html"; orig = f.read_text(encoding="utf-8")
        f.write_text(orig.replace('<option value="tiwani">Tiwani</option>', "", 1), encoding="utf-8")
        try: rc, out = run(self.d, "check_site.py"); self.assertEqual(rc, 1); self.assertIn("branch options differ", out)
        finally: f.write_text(orig, encoding="utf-8")
    def test_rebuild_is_idempotent(self):
        before = {p: p.read_bytes() for p in (self.d / "branches").glob("*.html")}; run(self.d, "build.py"); self.assertEqual(before, {p: p.read_bytes() for p in (self.d / "branches").glob("*.html")})

if __name__ == "__main__": unittest.main()
